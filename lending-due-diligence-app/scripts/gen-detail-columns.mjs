// Generates src/lib/detail-columns.ts from the Dataverse schema definition so the
// dynamic form only ever writes columns that actually exist.
// Usage: node scripts/gen-detail-columns.mjs
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { tables } from './schema-v2.mjs';

const DETAIL_BY_CODE = {
  LendingReview: 'ava_LddLendingReview',
  RiskAssessment: 'ava_LddRiskAssessmentCase',
  ComplianceMonitoring: 'ava_LddComplianceCase',
  EscalationManagement: 'ava_LddEscalationCase',
  QualityRecommendation: 'ava_LddQualityRecCase',
};

const byName = new Map(tables.map((t) => [t.schema, t]));

const lines = [
  '/**',
  ' * Columns available on each case-type detail table.',
  ' *',
  ' * GENERATED by scripts/gen-detail-columns.mjs - do not edit by hand.',
  ' * The dynamic form uses this to drop prototype fields that have no Dataverse',
  ' * column, instead of failing the whole save.',
  ' */',
  '',
  'export const DETAIL_COLUMNS: Record<string, ReadonlySet<string>> = {',
];

for (const [code, schemaName] of Object.entries(DETAIL_BY_CODE)) {
  const t = byName.get(schemaName);
  if (!t) throw new Error(`Unknown detail table ${schemaName}`);
  const cols = t.columns
    .filter((c) => c.kind !== 'lookup')
    .map((c) => c.name.toLowerCase())
    .concat('ava_name')
    .sort();
  lines.push(`  ${code}: new Set([`);
  for (const c of cols) lines.push(`    '${c}',`);
  lines.push('  ]),');
}

lines.push('};', '');

// Columns on the shared work case envelope that a form may write directly.
const workCase = byName.get('ava_LddWorkCase');
const wcCols = workCase.columns
  .filter((c) => c.kind !== 'lookup')
  .map((c) => c.name.toLowerCase())
  .sort();
lines.push('export const WORK_CASE_COLUMNS: ReadonlySet<string> = new Set([');
for (const c of wcCols) lines.push(`  '${c}',`);
lines.push(']);', '');

const out = fileURLToPath(new URL('../src/lib/detail-columns.ts', import.meta.url));
fs.writeFileSync(out, lines.join('\n'), 'utf8');
console.log(`wrote ${out}`);
